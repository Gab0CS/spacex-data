def _spacetrack(
    object_name: str,
    norad_id: int,
    decayed: int,
    *,
    epoch: str | None = None,
    mean_motion: float | None = None,
    eccentricity: float | None = None,
    inclination_deg: float | None = None,
    raan: float | None = None,
    arg_of_pericenter: float | None = None,
    mean_anomaly: float | None = None,
    semi_major_axis_km: float | None = None,
    period_min: float | None = None,
    apoapsis_km: float | None = None,
    periapsis_km: float | None = None,
    launch_date: str | None = None,
    decay_date: str | None = None,
) -> dict:
    return {
        **_SPACETRACK_DEFAULTS,
        "CREATION_DATE": epoch,
        "OBJECT_NAME": object_name,
        "OBJECT_ID": f"{launch_date[:4]}-{norad_id % 100:03d}A" if launch_date else None,
        "EPOCH": epoch,
        "MEAN_MOTION": mean_motion,
        "ECCENTRICITY": eccentricity,
        "INCLINATION": inclination_deg,
        "RA_OF_ASC_NODE": raan,
        "ARG_OF_PERICENTER": arg_of_pericenter,
        "MEAN_ANOMALY": mean_anomaly,
        "NORAD_CAT_ID": norad_id,
        "SEMIMAJOR_AXIS": semi_major_axis_km,
        "PERIOD": period_min,
        "APOAPSIS": apoapsis_km,
        "PERIAPSIS": periapsis_km,
        "LAUNCH_DATE": launch_date,
        "DECAY_DATE": decay_date,
        "DECAYED": decayed,
        "GP_ID": 100000 + norad_id,
        "TLE_LINE0": f"0 {object_name}",
        "TLE_LINE1": f"1 {norad_id}U {launch_date[2:4] if launch_date else '00'}001A   {(epoch or '')[2:4]}001.00000000  .00000000  00000-0  00000-0 0  9999",
        "TLE_LINE2": f"2 {norad_id} {inclination_deg or 0:8.4f} {raan or 0:8.4f} 0001000 {arg_of_pericenter or 0:8.4f} {mean_anomaly or 0:8.4f} {mean_motion or 0:11.8f}    10",
    }


def _satellite(
    sat_id: str,
    version: str,
    launch: str | None,
    *,
    object_name: str,
    norad_id: int,
    decayed: int = 0,
    longitude: float | None = None,
    latitude: float | None = None,
    height_km: float | None = None,
    velocity_kms: float | None = None,
    **spacetrack_kwargs: object,
) -> dict:
    return {
        "id": sat_id,
        "version": version,
        "launch": launch,
        "longitude": longitude,
        "latitude": latitude,
        "height_km": height_km,
        "velocity_kms": velocity_kms,
        "spaceTrack": _spacetrack(object_name, norad_id, decayed, **spacetrack_kwargs),
    }


